// Emits dist/tokens.css (CSS variables) from the compiled tokens so web has one source of truth.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { colors, radius, shadow } from "../dist/index.js";

const kebab = (s) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const lines = [];
for (const [k, v] of Object.entries(colors)) lines.push(`  --${kebab(k)}: ${v};`);
for (const [k, v] of Object.entries(radius)) lines.push(`  --radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(shadow)) lines.push(`  --shadow-${k}: ${v};`);

const css = `/* Generated by scripts/build-css.mjs. Do not edit. */\n:root {\n${lines.join("\n")}\n}\n`;
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "dist", "tokens.css");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
