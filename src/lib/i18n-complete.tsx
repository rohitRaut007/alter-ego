interface LanguageContextType {
  language: string;
  setLanguage: (lang: string) => void;
  t: (key: string, fallback?: string) => string;
  currentLanguageSpec: Language;
}

const LanguageContext = createContext<LanguageContextType | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<string>(() => {
    if (typeof window !== "undefined") {
      const saved = localStorage.getItem("alter_ego_lang");
      if (saved && SUPPORTED_LANGUAGES.some((l) => l.code === saved)) {
        return saved;
      }
    }
    return DEFAULT_LANGUAGE;
  });

  const setLanguage = (lang: string) => {
    if (SUPPORTED_LANGUAGES.some((l) => l.code === lang)) {
      setLanguageState(lang);
      if (typeof window !== "undefined") {
        localStorage.setItem("alter_ego_lang", lang);
      }
    }
  };

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[language];
    if (langDict && langDict[key]) {
      return langDict[key]!;
    }
    const defaultDict = TRANSLATIONS[DEFAULT_LANGUAGE] || {};
    if (defaultDict[key]) {
      return defaultDict[key]!;
    }
    return fallback || key;
  };

  const currentLanguageSpec =
    SUPPORTED_LANGUAGES.find((l) => l.code === language) || SUPPORTED_LANGUAGES[0]!;

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, currentLanguageSpec }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return ctx;
}
